/**
 * Point 54: the cryptographic components, tested the way cryptographic code has to be —
 * against published vectors first, and then against everything an attacker would send.
 *
 * The nine kinds the brief asks for, and where they are:
 *
 * | Kind | Here | Also |
 * | --- | --- | --- |
 * | known-answer | `describe("known answers")` | RFC 5869 HKDF vectors in `hkdf.test.ts`, BIP-39 in `recovery.test.ts` |
 * | negative | `describe("negative")` | signature refusals in `protocol.test.ts` |
 * | malformed input | `describe("malformed input")` | `padding.test.ts`, `uploads.test.ts` |
 * | replay | `describe("replay")` | consumed-message replay in `protocol.test.ts` |
 * | corrupted ciphertext | `describe("corrupted ciphertext")` | backup tampering in `backup.test.ts` |
 * | wrong key | `describe("the wrong key")` | vault round-trip in `protocol.test.ts` |
 * | wrong identity | `describe("the wrong identity")` | safety numbers in `verification.test.ts` |
 * | nonce misuse | `describe("nonces")` | — |
 * | session reset | `describe("session reset")` | linking in `linking.test.ts` |
 *
 * Vectors are copied from the specifications, not generated by this code: a known-answer
 * test whose answer came out of the implementation it tests proves only that the code is
 * deterministic.
 */
